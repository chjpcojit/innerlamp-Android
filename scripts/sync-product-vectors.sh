#!/usr/bin/env bash
# Copies the shared product test vectors of the Calendar feature from the backend repo (innerlamp-be)
# into app/src/test/resources/product/calendar/rules/ and records the source in a SOURCE file.
# The copies are NEVER edited by hand. event-placement.json is backend-only (product spec 4.1): not copied.
# Sao chép vector test dùng chung của Lịch lễ từ repo backend vào app/src/test/resources/... và ghi
# SOURCE. Không sửa tay các bản sao. event-placement.json chỉ dành cho backend: không sao chép.
#
# Usage: scripts/sync-product-vectors.sh [path-to-innerlamp-be]   (default: ../innerlamp-be)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BE="${1:-$ROOT/../innerlamp-be}"
RULES_SRC="$BE/docs/product/calendar/rules"
DEST="$ROOT/app/src/test/resources/product/calendar/rules"
FILES=(countdown ordering home-block)

[ -d "$RULES_SRC" ] || { echo "Not found: $RULES_SRC" >&2; exit 1; }
COMMIT="$(git -C "$BE" rev-parse --short HEAD)"
if [ -n "$(git -C "$BE" status --porcelain -- docs/product/calendar/rules)" ]; then
  echo "Backend rules have uncommitted changes; commit them first so SOURCE is accurate." >&2
  exit 1
fi

mkdir -p "$DEST"
{
  echo "# Generated by scripts/sync-product-vectors.sh - do not edit by hand."
  echo "repo=innerlamp-be"
  echo "commit=$COMMIT"
} > "$DEST/SOURCE"
for name in "${FILES[@]}"; do
  cp "$RULES_SRC/$name.json" "$DEST/$name.json"
  version="$(sed -n 's/.*"product_spec_version": *"\([^"]*\)".*/\1/p' "$DEST/$name.json" | head -1)"
  echo "$name.json product_spec_version=$version" >> "$DEST/SOURCE"
done
echo "Synced calendar vectors from innerlamp-be @ $COMMIT into $DEST"
