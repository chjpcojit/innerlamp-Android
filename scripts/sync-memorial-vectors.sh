#!/usr/bin/env bash
# Copies the shared product test vectors of the Memorial feature from the backend repo (innerlamp-be) into
# app/src/test/resources/product/memorial/rules/ and records the source in a SOURCE file.
# The copies are NEVER edited by hand. reminder-moment.json is backend-only (product spec 4.3): not copied.
# Sao chép vector test dùng chung của Sổ giỗ từ repo backend vào app/src/test/resources/... và ghi SOURCE.
# Không sửa tay các bản sao. reminder-moment.json chỉ dành cho backend: không sao chép.
#
# Usage: scripts/sync-memorial-vectors.sh [path-to-innerlamp-be]   (default: ../innerlamp-be)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BE="${1:-$ROOT/../innerlamp-be}"
RULES_SRC="$BE/docs/product/memorial/rules"
DEST="$ROOT/app/src/test/resources/product/memorial/rules"
FILES=(death-date-conversion next-anniversary anniversary-ordinal)

[ -d "$RULES_SRC" ] || { echo "Not found: $RULES_SRC" >&2; exit 1; }
COMMIT="$(git -C "$BE" rev-parse --short HEAD)"
if [ -n "$(git -C "$BE" status --porcelain -- docs/product/memorial/rules)" ]; then
  echo "Backend rules have uncommitted changes; commit them first so SOURCE is accurate." >&2
  exit 1
fi

mkdir -p "$DEST"
{
  echo "# Generated by scripts/sync-memorial-vectors.sh - do not edit by hand."
  echo "repo=innerlamp-be"
  echo "commit=$COMMIT"
} > "$DEST/SOURCE"
for name in "${FILES[@]}"; do
  cp "$RULES_SRC/$name.json" "$DEST/$name.json"
  version="$(sed -n 's/.*"product_spec_version": *"\([^"]*\)".*/\1/p' "$DEST/$name.json" | head -1)"
  echo "$name.json product_spec_version=$version" >> "$DEST/SOURCE"
done
echo "Synced memorial vectors from innerlamp-be @ $COMMIT into $DEST"
